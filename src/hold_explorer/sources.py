"""Replaceable data-source adapters.

A SourceSpec describes how to map ANY tabular ADS-B export to the canonical schema.
To use another dataset, add a spec here - no other code changes.

IMPORTANT: Only use datasets whose licence/terms permit your use. Check before collecting.
The specs below describe column layouts only; they do not grant any data access.
"""
from dataclasses import dataclass


@dataclass
class SourceSpec:
    name: str
    columns: dict                      # canonical name -> source column name
    ts_kind: str = "iso"               # "iso" | "epoch_s"
    alt_unit: str = "m"                # "m" | "ft"
    speed_unit: str = "mps"            # "mps" | "kt" | "kmh"
    estimated_col: str | None = None   # column flagging estimated/interpolated positions
    estimated_values: tuple = ("1", "true", "t", "yes", "estimated", "mlat", "interpolated")
    attribution: str = ""
    licence_note: str = "UNKNOWN - verify before use"


SPECS = {
    # Matches data/sample/sample_adsb.csv produced by synth.py (raw units on purpose,
    # so the normalisation code is exercised).
    "sample_synthetic": SourceSpec(
        name="sample_synthetic",
        columns=dict(timestamp="time_iso", icao24="icao24", callsign="callsign",
                     lat="latitude", lon="longitude", alt="altitude_ft",
                     gs="groundspeed_kt", track="track", source="source"),
        ts_kind="iso", alt_unit="ft", speed_unit="kt", estimated_col="estimated",
        attribution="Synthetic data generated by hold_explorer.synth (no real aircraft).",
        licence_note="Synthetic - free to use.",
    ),
    # EXAMPLE column layout of an OpenSky-style state-vector export. Column names are a
    # template; verify against your actual file AND the dataset's terms of use.
    "state_vectors_example": SourceSpec(
        name="state_vectors_example",
        columns=dict(timestamp="time", icao24="icao24", callsign="callsign",
                     lat="lat", lon="lon", alt="baroaltitude", gs="velocity",
                     track="heading"),
        ts_kind="epoch_s", alt_unit="m", speed_unit="mps",
        attribution="(fill in the dataset's required attribution)",
        licence_note="Verify the provider's terms (research/non-commercial limits, redistribution).",
    ),
}
